/**
 * Bundles data/manuals/*.md and data/replay/*.json into TS/JSON modules importable by the app
 * (Vercel serverless has a read-only filesystem; static imports are bundled with the deploy).
 * Run: npx tsx scripts/build-data.ts   (also runs automatically before dev/build)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();

const manualsDir = join(root, 'data', 'manuals');
const manuals: Record<string, string> = {};
for (const f of readdirSync(manualsDir).filter((f) => f.endsWith('.md')).sort()) {
  manuals[f.replace(/\.md$/, '')] = readFileSync(join(manualsDir, f), 'utf8');
}
writeFileSync(
  join(root, 'data', 'manuals.generated.ts'),
  `// AUTO-GENERATED by scripts/build-data.ts – do not edit.\nexport const MANUALS: Record<string, string> = ${JSON.stringify(manuals, null, 2)};\n`,
);

const replayDir = join(root, 'data', 'replay');
const recs = readdirSync(replayDir)
  .filter((f) => f.endsWith('.json') && f !== 'index.json')
  .sort()
  .map((f) => JSON.parse(readFileSync(join(replayDir, f), 'utf8')));
writeFileSync(join(replayDir, 'index.json'), JSON.stringify(recs, null, 2) + '\n');

console.log(`build-data: ${Object.keys(manuals).length} manuals, ${recs.length} replay recordings`);
